test('folder navigation ignores late responses and keeps failed creation recoverable', async ({ page }) => {
  const demo = await mockLibrary(page);
  let release!: () => void;
  let started!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const pending = new Promise<void>(resolve => { started = resolve; });
  let releaseInitial!: () => void;
  const initial = new Promise<void>(resolve => { releaseInitial = resolve; });
  let first = true;
  await page.route('**/api/fs?*', async route => {
    const path = new URL(route.request().url()).searchParams.get('path') ?? '';
    if (first) { first = false; await initial; }
    if (path.endsWith('Slow')) { started(); await gate; }
    await route.fulfill({ json: { path, parent: '', home: DEMO_ROOT, kind: 'empty', entries: [] } });
  });
  await page.goto('/settings');
  await page.getByRole('button', { name: '切换素材库', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '切换素材库', exact: true });
  const path = dialog.getByRole('textbox', { name: '文件夹路径，可以直接粘贴后回车', exact: true });
  await path.fill(`${DEMO_ROOT}\\Slow`);
  releaseInitial();
  await expect(dialog.locator('.picker-list')).toHaveAttribute('aria-busy', 'false');
  await expect(path).toHaveValue(`${DEMO_ROOT}\\Slow`);
  await expect(dialog.getByRole('button', { name: '切换到这里', exact: true })).toBeDisabled();
  await path.press('Enter');
  await pending;
  await path.fill(`${DEMO_ROOT}\\Latest`);
  await path.press('Enter');
  await expect(dialog.locator('.picker-list')).toHaveAttribute('aria-busy', 'false');
  release();
  await expect(path).toHaveValue(`${DEMO_ROOT}\\Latest`);
  await dialog.getByRole('button', { name: '新建文件夹', exact: true }).click();
  await dialog.getByRole('textbox', { name: '新文件夹名称', exact: true }).fill('Created');
  demo.failures.add('POST /api/fs/mkdir');
  await dialog.getByRole('button', { name: '新建', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('演示请求失败');
  await expect(dialog.getByRole('textbox', { name: '新文件夹名称', exact: true })).toHaveValue('Created');
  await expect(dialog.getByRole('button', { name: '切换到这里', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: '新建', exact: true }).click();
  await expect(path).toHaveValue(`${DEMO_ROOT}\\Latest\\Created`);
  await dialog.screenshot({ path: 'test-results/folder-picker-workflow.png' });
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  expect(demo.unexpected).toEqual([]);
});

